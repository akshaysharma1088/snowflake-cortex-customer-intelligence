-- Run after sql/02_enrich.sql and sql/03_views.sql.
-- These checks display observed Snowflake results, not expected/model results.
USE DATABASE CORTEX_CI_DEMO;
USE SCHEMA APP;
SELECT COUNT(*) AS RAW_CONVERSATIONS, COUNT(DISTINCT CONVERSATION_ID) AS UNIQUE_IDS
FROM CONVERSATIONS;
SELECT STATUS, COUNT(*) AS ROWS FROM ENRICHED_CONVERSATIONS
GROUP BY STATUS ORDER BY STATUS;
SELECT CONVERSATION_ID, SENTIMENT_RAW:categories AS SENTIMENT_CATEGORIES,
       EXTRACTION_RAW:response AS EXTRACTED_ENTITIES,
       ISSUE_CLASSIFICATION_RAW:labels AS ISSUE_LABELS
FROM V_LATEST_ENRICHMENT
ORDER BY CONVERSATION_ID LIMIT 12;
SELECT COUNT(*) AS JOINED_ROWS,
       COUNT_IF(SENTIMENT_RAW IS NOT NULL) AS ENRICHED_ROWS
FROM V_CONVERSATION_INTELLIGENCE;
-- Check potential duplicates before publication.
SELECT CONVERSATION_ID, COUNT(*) AS DUPLICATES
FROM CONVERSATIONS GROUP BY CONVERSATION_ID HAVING COUNT(*) > 1;
