-- Stage the CSV first from SnowSQL or Snowflake CLI:
-- PUT file://./data/conversations.csv @%CONVERSATIONS AUTO_COMPRESS=FALSE OVERWRITE=TRUE;
USE DATABASE CORTEX_CI_DEMO;
USE SCHEMA APP;
CREATE FILE FORMAT IF NOT EXISTS CSV_DEMO TYPE=CSV
 FIELD_OPTIONALLY_ENCLOSED_BY='"' SKIP_HEADER=1 NULL_IF=('', 'NULL')
 TIMESTAMP_FORMAT='YYYY-MM-DD HH24:MI:SS';
COPY INTO CONVERSATIONS
FROM @%CONVERSATIONS/conversations.csv
FILE_FORMAT=(FORMAT_NAME=CSV_DEMO)
ON_ERROR='ABORT_STATEMENT';