CREATE DATABASE IF NOT EXISTS CORTEX_CI_DEMO;
CREATE SCHEMA IF NOT EXISTS CORTEX_CI_DEMO.APP;
CREATE WAREHOUSE IF NOT EXISTS CORTEX_CI_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
USE DATABASE CORTEX_CI_DEMO;
USE SCHEMA APP;
CREATE TABLE IF NOT EXISTS CONVERSATIONS (
 CONVERSATION_ID VARCHAR,
 CREATED_AT TIMESTAMP_NTZ,
 CHANNEL VARCHAR,
 PRODUCT VARCHAR,
 TRANSCRIPT VARCHAR,
 GOLD_SENTIMENT VARCHAR,
 GOLD_ISSUE VARCHAR,
 GOLD_UNRESOLVED BOOLEAN
);
CREATE TABLE IF NOT EXISTS ENRICHED_CONVERSATIONS (
 CONVERSATION_ID VARCHAR,
 ENRICHMENT_VERSION VARCHAR,
 RUN_ID VARCHAR,
 ENRICHED_AT TIMESTAMP_NTZ,
 SENTIMENT_RAW VARIANT,
 EXTRACTION_RAW VARIANT,
 ISSUE_CLASSIFICATION_RAW VARIANT,
 STATUS VARCHAR,
 ERROR_MESSAGE VARCHAR
);
CREATE TABLE IF NOT EXISTS ENRICHMENT_RUNS (
 RUN_ID VARCHAR, STARTED_AT TIMESTAMP_NTZ, FINISHED_AT TIMESTAMP_NTZ,
 INPUT_COUNT INTEGER, SUCCESS_COUNT INTEGER, FAILURE_COUNT INTEGER, VERSION VARCHAR
);