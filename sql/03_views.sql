USE DATABASE CORTEX_CI_DEMO;
USE SCHEMA APP;
CREATE OR REPLACE VIEW V_LATEST_ENRICHMENT AS
SELECT * FROM ENRICHED_CONVERSATIONS WHERE STATUS='SUCCESS'
QUALIFY ROW_NUMBER() OVER
 (PARTITION BY CONVERSATION_ID ORDER BY ENRICHED_AT DESC, RUN_ID DESC)=1;
CREATE OR REPLACE VIEW V_CONVERSATION_INTELLIGENCE AS
SELECT c.CONVERSATION_ID,c.CREATED_AT,c.CHANNEL,c.PRODUCT,c.TRANSCRIPT,
 c.GOLD_SENTIMENT,c.GOLD_ISSUE,c.GOLD_UNRESOLVED,e.ENRICHMENT_VERSION,
 e.SENTIMENT_RAW,e.EXTRACTION_RAW,e.ISSUE_CLASSIFICATION_RAW
FROM CONVERSATIONS c LEFT JOIN V_LATEST_ENRICHMENT e
 ON c.CONVERSATION_ID=e.CONVERSATION_ID;