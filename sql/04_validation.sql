USE DATABASE CORTEX_CI_DEMO;
USE SCHEMA APP;
SELECT COUNT(*) AS total_rows, COUNT(DISTINCT CONVERSATION_ID) AS unique_ids
FROM CONVERSATIONS;
SELECT COUNT(*) AS enriched_rows FROM V_LATEST_ENRICHMENT;
SELECT STATUS, COUNT(*) FROM ENRICHED_CONVERSATIONS GROUP BY STATUS;
SELECT c.CONVERSATION_ID
FROM CONVERSATIONS c LEFT JOIN V_LATEST_ENRICHMENT e
ON c.CONVERSATION_ID=e.CONVERSATION_ID
WHERE e.CONVERSATION_ID IS NULL ORDER BY c.CONVERSATION_ID;